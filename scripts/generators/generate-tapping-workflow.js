function validateProjection(profileProjection, tapTypeProjection) {
  const errors = [];
  if (profileProjection.projection_type !== "tapping_profile_projection") {
    errors.push("profileProjection.projection_type mismatch");
  }
  if (tapTypeProjection.projection_type !== "tapping_tap_type_projection") {
    errors.push("tapTypeProjection.projection_type mismatch");
  }
  if (!Array.isArray(profileProjection.rows) || profileProjection.rows.length === 0) {
    errors.push("profileProjection.rows missing or empty");
  }
  if (!Array.isArray(tapTypeProjection.rows) || tapTypeProjection.rows.length !== 7) {
    errors.push(`Expected 7 tap-type rows, found ${(tapTypeProjection.rows || []).length}`);
  }
  for (const row of profileProjection.rows || []) {
    for (const field of ["tapping_profile_id", "thread", "tap_drill", "tap_types", "standards", "data_quality"]) {
      if (!(field in row)) errors.push(`Row ${row.tapping_profile_id || "unknown"} missing ${field}`);
    }
  }
  for (const row of tapTypeProjection.rows || []) {
    for (const field of ["entity_id", "general_taxonomy", "manufacturing_characteristics", "typical_applications", "manufacturer_specific_recommendations"]) {
      if (!(field in row)) errors.push(`Tap type ${row.entity_id || "unknown"} missing ${field}`);
    }
  }
  return errors;
}

function main() {
  const root = projectRoot();
  const profileProjection = readJson(path.join(root, "data", "projections", "tapping", "tapping-profiles.json"));
  const tapTypeProjection = readJson(path.join(root, "data", "projections", "tapping", "tap-types.json"));

  const errors = validateProjection(profileProjection, tapTypeProjection);
  if (errors.length) {
    console.error("Tapping workflow projection validation failed:");
    for (const e of errors) console.error(`- ${e}`);
    process.exit(1);
  }

  const data = buildWorkflowData(profileProjection, tapTypeProjection);

  writeText(path.join(root, "js", "tapping-workflow-data.js"), renderDataFile(data));
  console.log(`Generated js/tapping-workflow-data.js (${data.profiles.length} profiles, ${data.tapTypes.length} tap types)`);

  writeText(path.join(root, "tools", "tapping-workflow.html"), renderHtml());
  console.log("Generated tools/tapping-workflow.html");
}

main();
