function escapeHtml(text) {
  return String(text)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

// -- Build a lean client-side data shape from the T3 projections, preserving every field the
// workflow needs, dropping nothing that would be silently lost. This file is generated FROM the
// projection at build time; it is not a second authored data source. --
function buildWorkflowData(profileProjection, tapTypeProjection) {
  const profiles = profileProjection.rows.map((row) => ({
    id: row.tapping_profile_id,
    thread: row.thread,
    tap_drill: row.tap_drill,
    alternative_drill: row.alternative_drill,
    engagement: row.engagement,
    tap_types: row.tap_types,
    standards: row.standards,
    data_quality: row.data_quality
  }));

  const tapTypes = tapTypeProjection.rows
    .slice()
    .sort((a, b) => TAP_TYPE_ORDER.indexOf(a.entity_id) - TAP_TYPE_ORDER.indexOf(b.entity_id))
    .map((row) => ({
      entity_id: row.entity_id,
      title: row.title,
      definition: row.definition,
      general_taxonomy: row.general_taxonomy,
      manufacturing_characteristics: row.manufacturing_characteristics,
      typical_applications: row.typical_applications,
      manufacturer_specific_recommendations: row.manufacturer_specific_recommendations
    }));

  return { profiles, tapTypes };
}

